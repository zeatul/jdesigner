package glz.hawk.jdesigner.builder.factory.database.index;

/**
 * This class is responsible for providing necessary information for {@link IndexSupplierFactory} to build a {@code Index}.
 *
 * @author Hawk
 */
public class IndexFactoryContext extends IndexFactoryContextSupport {

    private String name;

    private boolean unique;

    private String shortName;

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public boolean isUnique() {
        return unique;
    }

    public void setUnique(boolean unique) {
        this.unique = unique;
    }

    public String getShortName() {
        return shortName;
    }

    public void setShortName(String shortName) {
        this.shortName = shortName;
    }
}
